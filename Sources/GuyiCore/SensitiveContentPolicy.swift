import Foundation

/// Metadata is checked before reading clipboard text. Text heuristics are only
/// an additional safeguard; a natural-language password cannot be inferred.
public enum SensitiveContentPolicy {
    public static func protectedApplication(_ identifier: String?) -> Bool {
        guard let id = identifier?.lowercased() else { return false }
        return ["com.1password.", "com.agilebits.", "com.bitwarden.", "com.dashlane.",
                "org.keepassxc.", "com.enpass.", "com.lastpass."].contains { id.hasPrefix($0) } ||
            ["com.apple.passwords", "com.apple.keychainaccess", "com.bitwarden.desktop"].contains(id)
    }
    public static func blocksClipboard(types: [String], source: String?, foreground: String?) -> Bool {
        if protectedApplication(source) || protectedApplication(foreground) { return true }
        return types.contains {
            let value = $0.lowercased()
            return value.contains("concealed") || value.contains("transient") ||
                value.contains("autogenerated") || value.contains("password") ||
                value.hasPrefix("com.agilebits.")
        }
    }
    public static func resemblesSecret(_ text: String) -> Bool {
        let value = text.trimmingCharacters(in: .whitespacesAndNewlines)
        func matches(_ pattern: String) -> Bool { value.range(of: pattern, options: .regularExpression) != nil }
        if matches(#"(?i)-----BEGIN (?:RSA |EC |OPENSSH |DSA )?PRIVATE KEY-----"#) { return true }
        if matches(#"(?i)^(?:password|passwd|pwd|api[_ -]?key|access[_ -]?token|secret)\s*[:=]\s*\S+"#) { return true }
        guard !value.contains(where: { $0.isWhitespace }) else { return false }
        if matches(#"^(?:sk[-_]|ghp_|github_pat_|AKIA)[A-Za-z0-9_-]{8,}$"#) { return true }
        if matches(#"^eyJ[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+$"#) { return true }
        if matches(#"^(?=.*[A-Za-z])(?=.*[0-9])(?=.*[^A-Za-z0-9])[\x21-\x7e]{6,}$"#) { return true }
        if matches(#"^(?=.*[A-Za-z])(?=.*[0-9])[A-Za-z0-9]{8,}$"#) { return true }
        // Long encoded blobs are not language, even without digits.
        if value.count >= 32, matches(#"^[A-Za-z0-9+/=_-]+$"#) { return true }
        return false
    }
}
